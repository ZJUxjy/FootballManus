"""Random player generator using normal distribution.

Generates realistic football players with attributes following normal distributions
based on real-world football statistics.
"""

import random
import numpy as np
from typing import Dict, List, Optional, Tuple
from dataclasses import dataclass
from enum import Enum


class PlayerPosition(Enum):
    """Player positions on the field."""

    GK = "GK"
    CB = "CB"  # Center Back
    LB = "LB"  # Left Back
    RB = "RB"  # Right Back
    DM = "DM"  # Defensive Midfielder
    CM = "CM"  # Central Midfielder
    LM = "LM"  # Left Midfielder
    RM = "RM"  # Right Midfielder
    AM = "AM"  # Attacking Midfielder
    LW = "LW"  # Left Winger
    RW = "RW"  # Right Winger
    ST = "ST"  # Striker


@dataclass
class PlayerGenerationConfig:
    """Configuration for player generation."""

    # Age distribution (normal distribution)
    age_mean: float = 25.0
    age_std: float = 4.5
    age_min: int = 16
    age_max: int = 40

    # Current ability distribution
    ca_mean: float = 15.0
    ca_std: float = 6.0
    ca_min: int = 0
    ca_max: int = 100

    # Potential ability (independent normal distribution, must be >= CA)
    pa_mean: float = 15.0
    pa_std: float = 2.5
    pa_min: int = 0
    pa_max: int = 100

    position_weights: Optional[Dict[str, float]] = None

    def __post_init__(self):
        if self.position_weights is None:
            # Realistic distribution: more defenders and midfielders
            self.position_weights = {
                "GK": 0.08,
                "CB": 0.14,
                "LB": 0.07,
                "RB": 0.07,
                "DM": 0.08,
                "CM": 0.15,
                "LM": 0.05,
                "RM": 0.05,
                "AM": 0.08,
                "LW": 0.06,
                "RW": 0.06,
                "ST": 0.11,
            }


@dataclass
class GeneratedPlayer:
    """A generated player with all attributes."""

    id: int
    full_name: str
    age: int
    position: str
    nationality: str
    current_ability: float
    potential_ability: float
    market_value: int
    weekly_wage: int
    height: int  # cm
    weight: int  # kg
    preferred_foot: str

    def to_dict(self) -> Dict:
        """Convert to dictionary format."""
        return {
            "id": self.id,
            "full_name": self.full_name,
            "age": self.age,
            "position": self.position,
            "nationality": self.nationality,
            "current_ability": round(self.current_ability, 1),
            "potential_ability": round(self.potential_ability, 1),
            "market_value": self.market_value,
            "weekly_wage": self.weekly_wage,
            "height": self.height,
            "weight": self.weight,
            "preferred_foot": self.preferred_foot,
        }


